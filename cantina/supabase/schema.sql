create table if not exists public.itens (
  id bigint generated by default as identity primary key,
  nome varchar(50) not null,
  preco numeric(8, 2) not null check (preco >= 0),
  emoji varchar(10),
  categoria varchar(20) not null,
  esgotado boolean not null default false
);

create table if not exists public.pedidos (
  id bigint generated by default as identity primary key,
  nome_cliente varchar(30) not null,
  status varchar(20) not null default 'recebido',
  total numeric(8, 2) not null check (total >= 0),
  criado_em timestamptz not null default now()
);

create table if not exists public.pedido_itens (
  id bigint generated by default as identity primary key,
  pedido_id bigint not null references public.pedidos(id) on delete cascade,
  item_id bigint not null references public.itens(id),
  quantidade integer not null check (quantidade between 1 and 10),
  preco_unitario numeric(8, 2) not null check (preco_unitario >= 0)
);

create index if not exists pedido_itens_pedido_id_idx on public.pedido_itens(pedido_id);

